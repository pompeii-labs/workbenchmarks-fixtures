// Rebuild the checked-in resource; no credentials or runtime network dependency.
import { writeFile } from 'node:fs/promises';

const sourceUrl = 'https://re.jrc.ec.europa.eu/api/v5_3/tmy?lat=44.98&lon=-93.27&outputformat=json';
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`PVGIS HTTP ${response.status}`);
const data = await response.json();
const rows = data.outputs.tmy_hourly;
if (rows.length !== 8760) throw new Error('Expected a non-leap 8760-hour TMY');
const hourly = rows.map((row, i) => {
  const expected = new Date(Date.UTC(2027, 0, 1, i)).toISOString();
  const suffix = expected.slice(5, 10).replace('-', '') + ':' + expected.slice(11, 13) + '00';
  if (row['time(UTC)'].slice(4) !== suffix) throw new Error(`Unexpected timestamp at ${i}`);
  const values = ['G(h)', 'Gb(n)', 'Gd(h)', 'T2m'].map(key => row[key]);
  if (!values.every(Number.isFinite)) throw new Error(`Invalid resource row ${i}`);
  return values;
});
const provenance = {
  sourceUrl,
  retrievedAt: new Date().toISOString(),
  inputs: data.inputs,
  monthsSelected: data.outputs.months_selected,
  metadata: data.meta,
  columns: ['ghiWm2', 'dniWm2', 'dhiWm2', 'airTemperatureC'],
  ordering: '8760 UTC hours, January 1 00:00 through December 31 23:00; source month/year selections retained above.',
};
await writeFile(new URL('./minneapolis-tmy.js', import.meta.url),
  '// Generated by fetch-resource.mjs from the public PVGIS API. Do not hand-edit.\n' +
  `export const RESOURCE_PROVENANCE = ${JSON.stringify(provenance, null, 2)};\n` +
  'export const HOURLY_RESOURCE = [\n' + hourly.map(row => JSON.stringify(row)).join(',\n') + '\n];\n');
console.log(`Saved ${hourly.length} hourly PVGIS-ERA5 records.`);
